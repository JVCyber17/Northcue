// Corpus documents built from PUBLISHED SPECIFICATIONS rather than from our
// idea of a letter. CORPUS_STRATEGY.md, Track 2.
//
// WHY A SEPARATE FILE. corpus.js is already 1,400 lines and these documents are
// long on purpose. They are also built differently from everything else: each
// field below is present because a regulation, a licence condition or a
// prescribed form requires it, not because it seemed realistic.
//
// THE PROBLEM THEY EXIST FOR. Before these, the median corpus document was 62
// words and the longest was 171. A real UK energy bill is 1,800 to 4,000 words
// across several pages. Nothing above 171 words had ever been tested, so every
// behaviour that only appears at real length was untested: competing labels far
// apart, a deadline on page three, the same amount repeated across sections, a
// statutory notes block longer than the letter it explains.
//
// WHERE THE FIELD LISTS COME FROM. Named per document so the reason a field is
// present is a citation rather than a guess. Values are invented; structure is
// not. No real person, account, meter or property appears.
//
// PAGE BREAKS. Each document declares its own, with a "\f" marker line, so
// scripts/corpus-pdf/generate.js can lay it out as a real multi-page PDF and
// the round trip covers it. The engine never sees the marker: corpus.js strips
// it, and the PDF writer splits on it.

